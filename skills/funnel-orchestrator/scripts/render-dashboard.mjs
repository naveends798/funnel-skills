// Assemble all asset JSONs (and the design folder) into a single run.js the dashboard can load.
// Copies the dashboard template into output/<slug>/dashboard/ and writes run.js inside it.
//
// usage: node render-dashboard.mjs <slug>

import { readFileSync, writeFileSync, existsSync, mkdirSync, copyFileSync, readdirSync } from 'node:fs';
import { join, dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { homedir } from 'node:os';
import { normalizeRun } from '../../../lib/normalize.mjs';

const ROOT = process.cwd();
const slug = process.argv[2];
if (!slug) {
  console.error('usage: node render-dashboard.mjs <slug>');
  process.exit(1);
}

const clientDir = join(ROOT, 'output', slug);
if (!existsSync(clientDir)) {
  console.error(`No such client folder: ${clientDir}`);
  process.exit(1);
}

// Find the dashboard template — try in priority order:
//   1. $FUNNEL_SKILLS_HOME/dashboard
//   2. ~/.funnel-skills/dashboard
//   3. <cwd>/dashboard (when running inside the repo)
//   4. Walk up from this script's location to find a dashboard/ folder (dev mode)
function resolveFunnelSkillsHome() {
  if (process.env.CLAUDE_PLUGIN_ROOT && existsSync(join(process.env.CLAUDE_PLUGIN_ROOT, 'dashboard'))) {
    return process.env.CLAUDE_PLUGIN_ROOT;
  }
  if (process.env.FUNNEL_SKILLS_HOME && existsSync(join(process.env.FUNNEL_SKILLS_HOME, 'dashboard'))) {
    return process.env.FUNNEL_SKILLS_HOME;
  }
  const homeFs = join(homedir(), '.funnel-skills');
  if (existsSync(join(homeFs, 'dashboard'))) return homeFs;
  if (existsSync(join(ROOT, 'dashboard'))) return ROOT;
  // Walk up from this script
  const here = dirname(fileURLToPath(import.meta.url));
  let cur = here;
  for (let i = 0; i < 8; i++) {
    if (existsSync(join(cur, 'dashboard', 'index.html'))) return cur;
    const next = dirname(cur);
    if (next === cur) break;
    cur = next;
  }
  return ROOT; // fall back
}

const FUNNEL_SKILLS_HOME = resolveFunnelSkillsHome();
const dashboardSrc = join(FUNNEL_SKILLS_HOME, 'dashboard');
const dashboardDst = join(clientDir, 'dashboard');
mkdirSync(dashboardDst, { recursive: true });

// Copy dashboard template files
for (const f of ['index.html', 'style.css', 'app.js']) {
  const src = join(dashboardSrc, f);
  if (existsSync(src)) copyFileSync(src, join(dashboardDst, f));
}

function readJson(path, fallback = null) {
  return existsSync(path) ? JSON.parse(readFileSync(path, 'utf8')) : fallback;
}
function readText(path, fallback = '') {
  return existsSync(path) ? readFileSync(path, 'utf8') : fallback;
}

const rawRun = {
  slug,
  generated_at: new Date().toISOString(),
  intake: readJson(join(clientDir, 'intake.json')),
  market: readJson(join(clientDir, '01-market.json')),
  offer: readJson(join(clientDir, '02-offer.json')),
  strategy: readJson(join(clientDir, '03-strategy.json')),
  hooks: readJson(join(clientDir, '04-hooks.json')),
  page_copy: readJson(join(clientDir, '05-page-copy.json')),
  emails: readJson(join(clientDir, '06-emails.json')),
  vsl: readJson(join(clientDir, '07-vsl.json')),
  design: assembleDesign(clientDir),
  audit: readJson(join(clientDir, '09-audit.json')),
};

// Coerce sub-skill drift into the dashboard's expected contract.
// Source JSONs on disk are left untouched — only the bundle handed to the dashboard is normalized.
const run = normalizeRun(rawRun);

const runJsPath = join(dashboardDst, 'run.js');
writeFileSync(
  runJsPath,
  `// Auto-generated by render-dashboard.mjs at ${run.generated_at}\nwindow.__RUN__ = ${JSON.stringify(run)};\n`,
);

// Top-level launcher: index.html at output/<slug>/ that redirects into dashboard/.
// Lets users (and the orchestrator's auto-launch) point an HTTP server at output/<slug>/
// and have everything just work — including the iframe at ../08-design/landing.html.
writeFileSync(
  join(clientDir, 'index.html'),
  `<!doctype html><meta charset="utf-8"><title>${slug} — funnel-skills</title>` +
    `<meta http-equiv="refresh" content="0; url=dashboard/index.html">` +
    `<p>Loading dashboard… <a href="dashboard/index.html">click here</a> if it doesn't redirect.</p>\n`,
);

console.log(`✓ dashboard built → ${join(dashboardDst, 'index.html')}`);
console.log(`  run.js: ${(JSON.stringify(run).length / 1024).toFixed(1)}KB`);
console.log(`  launcher: ${join(clientDir, 'index.html')}`);

function assembleDesign(clientDir) {
  const designDir = join(clientDir, '08-design');
  if (!existsSync(designDir)) return null;
  return {
    landing_html: readText(join(designDir, 'landing.html')),
    landing_css: readText(join(designDir, 'landing.css')),
    landing_html_relative: '../08-design/landing.html', // for iframe src from dashboard/
    ghl_prompt: readText(join(designDir, 'ghl-ai-studio-prompt.md')),
    clickfunnels_prompt: readText(join(designDir, 'clickfunnels-ai-prompt.md')),
    framer_prompt: readText(join(designDir, 'framer-ai-prompt.md')),
    design_system: readJson(join(designDir, 'design-system.json')),
  };
}
